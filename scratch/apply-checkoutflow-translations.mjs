function serializeLang(obj) {
  let res = '{\n';
  for (const [k, v] of Object.entries(obj)) {
    if (typeof v === 'function') {
      res += `    ${k}: ${v.toString()},\n`;
    } else {
      res += `    ${k}: ${JSON.stringify(v)},\n`;
    }
  }
  res += '  }';
  return res;
}

